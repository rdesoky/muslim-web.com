/**
 * build_qtext_data.mjs — generates js/quran/qtext_data.js from the static
 * qtext/sura_*.html pages.
 *
 * The front-end previously fetched Quran aya text from PHP/CGI + MySQL
 * (quran_data table). The aya text is still present, rendered as static HTML
 * in qtext/sura_001.html .. sura_114.html. This tool parses each page's
 * <body> and produces a compact per-sura/aya lookup used by the client-side
 * CGI shim (js/quran/local_cgi.js) to serve:
 *   - get_aya_utf8.js.pl      (random/by-position aya {text,plain})
 *   - get_aya_list_utf8.js.pl (plain text list for a PageList)
 *   - get_sura_text.pl        (range display/copy)
 *   - search.pl               (LIKE search over plain text)
 *
 * Run from repo root:  node tools/build/build_qtext_data.mjs
 */

import { readFileSync, writeFileSync, existsSync } from "node:fs";

const AYA_COUNT = [
  7, 286, 200, 176, 120, 165, 206, 75, 129, 109, 123, 111, 43, 52, 99, 128, 111,
  110, 98, 135, 112, 78, 118, 64, 77, 227, 93, 88, 69, 60, 34, 30, 73, 54, 45,
  83, 182, 88, 75, 85, 54, 53, 89, 59, 37, 35, 38, 29, 18, 45, 60, 49, 62, 55,
  78, 96, 29, 22, 24, 13, 14, 11, 11, 18, 12, 12, 30, 52, 52, 44, 28, 28, 20,
  56, 40, 31, 50, 40, 46, 42, 29, 19, 36, 25, 22, 17, 19, 26, 30, 20, 15, 21,
  11, 8, 8, 19, 5, 8, 8, 11, 11, 8, 3, 9, 5, 4, 7, 3, 6, 3, 5, 4, 5, 6,
];

/** Remove HTML tags and decode the few entities the qtext pages use. */
function stripHtml(s) {
  return s
    .replace(/<[^>]+>/g, "")
    .replace(/&nbsp;/g, " ")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&amp;/g, "&")
    .replace(/&quot;/g, '"')
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * Extract the "plain" searchable text: strip Arabic tashkeel and normalise
 * the ambiguous characters the same way update_stext.pl did (alef/ha/hamza/yaa).
 */
function toPlain(text) {
  return text
    .replace(/[\u064B-\u0652\u0670\u0640]/g, "") // tashkeel + tatweel
    .replace(/[^\u0621-\u063A\u0641-\u064A ]/g, " ") // Arabic letters + space only
    .replace(/[أإآٱ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/[ئؤ]/g, "ء")
    .replace(/ى/g, "ي")
    .replace(/\s+/g, " ")
    .trim();
}

/** Split a sura page <body> into aya records. */
function parseSuraPage(body, sura) {
  const ayat = [];
  // each aya is <p aya="N"> ... </p>
  const re = /<p\s+aya="(\d+)"[^>]*>([\s\S]*?)<\/p>/g;
  let m;
  while ((m = re.exec(body))) {
    const n = parseInt(m[1], 10);
    // drop the aya-number span ("(N)") and the empty amenu marker
    let inner = m[2].replace(/<span\s+akey=["'][^"']*["']>[\s\S]*?<\/span>/gi, "");
    inner = inner.replace(/<span\s+amenu=["'][^"']*["'][^>]*>[\s\S]*?<\/span>/gi, "");
    while (ayat.length < n) ayat.push("");
    ayat[n - 1] = stripHtml(inner);
  }
  // sanity check
  const expected = AYA_COUNT[sura - 1];
  if (ayat.length !== expected) {
    console.warn(
      `  WARNING sura ${sura}: found ${ayat.length} ayat, expected ${expected}`,
    );
  }
  return ayat;
}

function main() {
  const out = [];
  out.push("// Generated by tools/build/build_qtext_data.mjs — do not edit.");
  out.push("// Plain-text Quran aya data used by the client-side CGI shim.");
  out.push("var QuranTextData = {");
  for (let sura = 1; sura <= 114; sura++) {
    const file = `qtext/sura_${String(sura).padStart(3, "0")}.html`;
    if (!existsSync(file)) {
      console.warn(`  SKIP ${file} (missing)`);
      continue;
    }
    const html = readFileSync(file, "utf8");
    const bodyMatch = /<body[^>]*>([\s\S]*?)<\/body>/i.exec(html);
    if (!bodyMatch) {
      console.warn(`  SKIP ${file} (no body)`);
      continue;
    }
    const ayat = parseSuraPage(bodyMatch[1], sura);
    const entries = [];
    for (let a = 1; a <= ayat.length; a++) {
      const text = ayat[a - 1];
      if (!text) continue;
      const plain = toPlain(text);
      // escape JS string safely
      const j = (s) =>
        JSON.stringify(s).replace(/</g, "\\u003c").replace(/>/g, "\\u003e");
      entries.push(`\t\t${a}:{t:${j(text)},p:${j(plain)}}`);
    }
    out.push(`\t${sura}:{\n${entries.join(",\n")}\n\t},`);
  }
  out.push("};");
  out.push("if (typeof window != 'undefined') window.QuranTextData = QuranTextData;");

  writeFileSync("js/quran/qtext_data.js", out.join("\n") + "\n", "utf8");
  console.log("Wrote js/quran/qtext_data.js");
}

main();
