sub ReplaceAmbChars
{
	my $sText = shift;
	
	my $retText = "";
	my $offset;
	my $curr_char;

	for ($offset =0; $offset < length($sText); $offset ++)
	{
		$curr_char = substr($sText,$offset,1);

		if (ord($curr_char) == 0xC2 or ord($curr_char) == 0xC3 or ord($curr_char) == 0xc5 ) {
			$curr_char = "«";
		}

		if (ord($curr_char) == 0xC9) {
			$curr_char = "Â";
		}

		$retText = $retText . $curr_char;
	}

	return $retText;
}
